    info = COUNTRY_DATA.get(code.lower())
    
    if not info:
        # No info -> Priority 3 (Last), sorted by code
        return (3, code.title())
        
    continent = info.get("continent", "OT")
    name = info.get("name", code)
    
    priority = 2
    if continent == "EU":
        priority = 0
    elif continent == "AS":
        priority = 1
        
    return (priority, name)
